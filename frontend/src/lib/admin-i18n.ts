export function translateAdminText(lang: Language, text: string): string {
  return lang === 'en' ? (en[text] ?? extraEn[text] ?? text) : text;
}

export function useAdminText() {
  const { lang } = useLanguage();
  return useCallback((text: string) => translateAdminText(lang, text), [lang]);
}
