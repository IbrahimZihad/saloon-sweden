export const dictionaries: Record<Language, Dictionary> = { sv, en };

export function translate(lang: Language, key: string, params?: Record<string, string | number>): string {
  let value = dictionaries[lang][key] ?? dictionaries[DEFAULT_LANGUAGE][key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      value = value.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return value;
}